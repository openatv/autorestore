#!/bin/sh
# Renders the fonts of the progress bar into fonts/.
#
#   tools/mkfonts.sh
#
# Needs Node.js for npx lv_font_conv on the host, not in the image.
set -e
cd "$(dirname "$0")/.."

# DejaVu Sans: ASCII, Latin-1 with the middle dot, ellipsis and warning sign.
TEXT="0x20-0x7E,0xA0-0xFF,0x2026,0x26A0"

render() {
	npx -y lv_font_conv --bpp 4 --size "$2" --format lvgl --font tools/fonts/DejaVuSans.ttf -r "$3" \
		--lv-include lvgl.h --lv-font-name "$1" -o "fonts/$1.c.tmp"
	{
		echo "/* Generated by tools/mkfonts.sh, do not edit. Rendered from DejaVu Sans 2.37"
		echo " * (Bitstream Vera and Arev licenses, tools/fonts/DejaVuSans-LICENSE.txt). */"
		sed -e :a -e '/^\n*$/{$d;N;ba' -e '}' "fonts/$1.c.tmp"  # Without the empty lines at the end.
	} > "fonts/$1.c"
	rm "fonts/$1.c.tmp"
}

for size in 16 24 30; do
	render "fbp_font_$size" "$size" "$TEXT"
done
